"use client";

import { useState } from "react";
import { AlertCircle, Check, Copy, Loader2 } from "lucide-react";
import type { Mode } from "@/lib/types";

export const fieldClass = "field";

export function Spinner() {
  return <Loader2 className="h-4 w-4 animate-spin" aria-hidden="true" />;
}

export function ErrorNote({ message }: { message: string }) {
  return (
    <p
      role="alert"
      className="mt-4 flex items-start gap-2 rounded-xl border border-accent/40 bg-accent/10 px-4 py-3 text-sm text-foreground"
    >
      <AlertCircle className="mt-0.5 h-4 w-4 shrink-0 text-accent" aria-hidden="true" />
      {message}
    </p>
  );
}

export function ModeNote({ mode }: { mode: Mode }) {
  return mode === "ai" ? (
    <p className="text-xs leading-relaxed text-text-secondary">
      Generated by AI. Read it over and make it yours before using it.
    </p>
  ) : (
    <p className="rounded-lg border border-border bg-background-secondary/60 px-3 py-2 text-xs leading-relaxed text-text-secondary">
      <strong className="font-semibold text-accent-secondary">Demo mode.</strong> This is ready-made or rule-based
      content, not AI. The AI assistant is not switched on for this site yet.
    </p>
  );
}

export function PrivacyNote() {
  return (
    <p className="mt-3 text-xs leading-relaxed text-text-secondary">
      When the AI assistant is on, what you type is sent to Google&apos;s Gemini API to create the result. GlowUp
      does not save it or log it in its own code, but the hosting service and the AI provider may keep their own
      records. Please avoid sharing passwords or sensitive personal details.
    </p>
  );
}

export function CopyButton({ text, label = "Copy" }: { text: string; label?: string }) {
  const [state, setState] = useState<"idle" | "copied" | "failed">("idle");

  async function copy() {
    try {
      await navigator.clipboard.writeText(text);
      setState("copied");
    } catch {
      setState("failed");
    }
    setTimeout(() => setState("idle"), 2200);
  }

  return (
    <button type="button" onClick={copy} className="btn btn-secondary btn-sm" aria-live="polite">
      {state === "copied" ? <Check className="h-4 w-4" aria-hidden="true" /> : <Copy className="h-4 w-4" aria-hidden="true" />}
      {state === "copied" ? "Copied" : state === "failed" ? "Couldn't copy" : label}
    </button>
  );
}
